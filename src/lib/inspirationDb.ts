export function pickTask(
  round: number,
  usedIds: number[]
): { entry: TaskEntry; resetIds: boolean } {
  const maxIntensity = getMaxIntensity(round);
  let available = TASKS_DB.filter(
    (t) => t.intensity <= maxIntensity && !usedIds.includes(t.id)
  );

  let resetIds = false;
  if (available.length === 0) {
    available = TASKS_DB.filter((t) => t.intensity <= maxIntensity);
    resetIds = true;
  }

  // Prefer tasks matching the current max intensity (weighted)
  const preferred = available.filter((t) => t.intensity === maxIntensity);
  const pool = preferred.length > 0 && Math.random() < 0.6 ? preferred : available;

  const entry = pool[Math.floor(Math.random() * pool.length)];
  return { entry, resetIds };
}

export function pickReward(
  round: number,
  usedIds: number[]
): { entry: RewardEntry; resetIds: boolean } {
  const maxIntensity = getMaxIntensity(round);
  let available = REWARDS_DB.filter(
    (r) => r.intensity <= maxIntensity && !usedIds.includes(r.id)
  );

  let resetIds = false;
  if (available.length === 0) {
    available = REWARDS_DB.filter((r) => r.intensity <= maxIntensity);
    resetIds = true;
  }

  const preferred = available.filter((r) => r.intensity === maxIntensity);
  const pool = preferred.length > 0 && Math.random() < 0.6 ? preferred : available;

  const entry = pool[Math.floor(Math.random() * pool.length)];
  return { entry, resetIds };
}
