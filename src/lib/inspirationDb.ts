/** Get a random task from the inspiration DB (no level gating for tasks) */
export function getRandomVerbatimTask(): GameContent {
  const entry = TASKS_DB[Math.floor(Math.random() * TASKS_DB.length)];
  return { title: entry.title, description: entry.description, drinkingRule: entry.drinkingRule };
}

/** Get a random reward from the inspiration DB, filtered by level */
export function getRandomVerbatimReward(level: number): GameContent {
  const available = REWARDS_DB.filter(r => !r.minLevel || level >= r.minLevel);
  const entry = available[Math.floor(Math.random() * available.length)];
  return { title: entry.title, description: entry.description, drinkingRule: entry.drinkingRule };
}

/** Build the full inspiration text for injecting into Gemini prompts */
export function getInspirationText(type: 'task' | 'reward', level: number): string {
  if (type === 'task') {
    return TASKS_DB.map(t => `• ${t.title}\n${t.description}\nעונש שתייה: ${t.drinkingRule}`).join('\n\n');
  }
  const available = REWARDS_DB.filter(r => !r.minLevel || level >= r.minLevel);
  return available.map(r => `• ${r.title}\n${r.description}\nכלל שתייה: ${r.drinkingRule}`).join('\n\n');
}
